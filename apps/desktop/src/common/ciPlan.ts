/**
 * CI/CD pipeline scaffolding (Phase 2 — CI/CD Pipeline).
 *
 * PURE module (no I/O, no Electron). A small model of a CI workflow (jobs → steps,
 * with `needs` dependencies + an optional build matrix), a validator (unique ids,
 * non-empty steps, and — reusing the DI container's graph helpers — missing-`needs`
 * + cycle detection), and a GitHub Actions YAML renderer. `defaultCiWorkflow()` is
 * this repo's pipeline (install → typecheck → format:check → build); the caller
 * writes the rendered YAML to `.github/workflows/ci.yml`.
 */

import { validateGraph, type DepGraph } from './serviceRegistry';

export interface CiStep {
  /** Step label (for `run` steps). */
  name?: string;
  /** A marketplace action, e.g. 'actions/checkout@v4'. */
  uses?: string;
  /** A shell command, e.g. 'npm ci'. */
  run?: string;
  /** Inputs for a `uses` action. */
  with?: Record<string, string>;
}

/** Build matrix: axis → values, e.g. { os: ['ubuntu-latest', 'windows-latest'] }. */
export type CiMatrix = Record<string, string[]>;

export interface CiJob {
  id: string;
  name?: string;
  /** Runner label, e.g. 'ubuntu-latest' or '${{ matrix.os }}'. */
  runsOn: string;
  /** Job ids that must complete first. */
  needs?: string[];
  matrix?: CiMatrix;
  steps: CiStep[];
}

export interface CiWorkflow {
  name: string;
  /** Trigger events, e.g. ['push', 'pull_request']. */
  on: string[];
  jobs: CiJob[];
}

export interface CiValidation {
  ok: boolean;
  issues: string[];
  summary: string;
}

/**
 * Validate a workflow: at least one job, unique ids, non-empty steps, and a sound
 * `needs` graph (no missing references, no cycles — via the shared graph helpers).
 */
export function validateWorkflow(wf: CiWorkflow): CiValidation {
  const issues: string[] = [];
  if (wf.jobs.length === 0) issues.push('no jobs defined');
  if (wf.on.length === 0) issues.push('no trigger events');
  const ids = new Set<string>();
  for (const j of wf.jobs) {
    if (ids.has(j.id)) issues.push(`duplicate job id "${j.id}"`);
    ids.add(j.id);
    if (j.steps.length === 0) issues.push(`job "${j.id}" has no steps`);
    for (const s of j.steps) {
      if (s.uses === undefined && s.run === undefined) {
        issues.push(`job "${j.id}" has a step with neither uses nor run`);
      }
    }
  }
  const graph: DepGraph = {};
  for (const j of wf.jobs) graph[j.id] = j.needs ?? [];
  const g = validateGraph(graph);
  if (!g.ok) issues.push(g.summary);
  const ok = issues.length === 0;
  return {
    ok,
    issues,
    summary: ok
      ? `Workflow "${wf.name}" OK — ${wf.jobs.length} job(s), triggers: ${wf.on.join(', ')}.`
      : `Workflow "${wf.name}" has ${issues.length} issue(s): ${issues.join('; ')}.`,
  };
}

/** Render a YAML scalar: quote numeric-looking or unsafe values, else plain. */
function yamlScalar(v: string): string {
  if (v.length === 0) return "''";
  if (/^[0-9]+(\.[0-9]+)?$/.test(v)) return `'${v}'`;
  if (/^[A-Za-z0-9_./\- ]+$/.test(v)) return v;
  return `'${v.replace(/'/g, "''")}'`;
}

/** Render a workflow to GitHub Actions YAML (2-space indented). */
export function renderWorkflowYaml(wf: CiWorkflow): string {
  const lines: string[] = [];
  lines.push('# Generated by Axiom (PRD Phase 2 — CI/CD). Edit the generator, not this file.');
  lines.push(`name: ${wf.name}`);
  lines.push('on:');
  for (const t of wf.on) lines.push(`  - ${t}`);
  lines.push('jobs:');
  for (const job of wf.jobs) {
    lines.push(`  ${job.id}:`);
    if (job.name !== undefined) lines.push(`    name: ${job.name}`);
    lines.push(`    runs-on: ${job.runsOn}`);
    if (job.needs && job.needs.length > 0) lines.push(`    needs: [${job.needs.join(', ')}]`);
    if (job.matrix && Object.keys(job.matrix).length > 0) {
      lines.push('    strategy:');
      lines.push('      matrix:');
      for (const [axis, vals] of Object.entries(job.matrix)) {
        lines.push(`        ${axis}: [${vals.map(yamlScalar).join(', ')}]`);
      }
    }
    lines.push('    steps:');
    for (const step of job.steps) {
      if (step.uses !== undefined) {
        lines.push(`      - uses: ${step.uses}`);
        if (step.with && Object.keys(step.with).length > 0) {
          lines.push('        with:');
          for (const [k, v] of Object.entries(step.with)) {
            lines.push(`          ${k}: ${yamlScalar(v)}`);
          }
        }
      } else {
        lines.push(`      - name: ${step.name ?? 'step'}`);
        lines.push(`        run: ${step.run ?? ''}`);
      }
    }
  }
  return `${lines.join('\n')}\n`;
}

/**
 * This repo's default pipeline: install, then the same gates the memory recipe runs
 * locally (typecheck · format check · build). Uses `npm run` (CI runners have no
 * PowerShell execution-policy restriction).
 */
export function defaultCiWorkflow(): CiWorkflow {
  return {
    name: 'CI',
    on: ['push', 'pull_request'],
    jobs: [
      {
        id: 'verify',
        name: 'Typecheck · Format · Build',
        runsOn: 'ubuntu-latest',
        steps: [
          { uses: 'actions/checkout@v4' },
          { uses: 'actions/setup-node@v4', with: { 'node-version': '20', cache: 'npm' } },
          { name: 'Install dependencies', run: 'npm ci' },
          { name: 'Typecheck', run: 'npm run typecheck' },
          { name: 'Format check', run: 'npm run format:check' },
          { name: 'Build', run: 'npm run build' },
        ],
      },
    ],
  };
}
