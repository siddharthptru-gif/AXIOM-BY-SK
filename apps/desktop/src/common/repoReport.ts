/**
 * "Explain this repo" report (T3.12). A pure Markdown builder over facts the Rust
 * Core already derives locally — project profile, dependency graph shape, import
 * cycles, and the guided tour stops. No model call, no network: the report is
 * evidence about the repository, so it must be reproducible and cite only what was
 * actually measured.
 *
 * Every count comes from a real measurement or is omitted. Sections whose input is
 * unavailable say so explicitly rather than being silently dropped, so a reader can
 * tell "none found" apart from "not analysed".
 */
import type { TourStop } from './repoTour';

export interface RepoReportInput {
  /** Workspace folder name (used as the report title). */
  name: string;
  /** Absolute workspace root, recorded so the report is traceable. */
  root: string;
  generatedAt: number;
  totalFiles: number;
  languages: ReadonlyArray<{ name: string; files: number }>;
  frameworks: readonly string[];
  packageManagers: readonly string[];
  testFramework: string | null;
  scripts: ReadonlyArray<{ name: string; command: string }>;
  entryPoints: readonly string[];
  monorepo: boolean;
  workspaces: readonly string[];
  /** Dependency-graph shape; null when the graph could not be built. */
  graph: { nodes: number; edges: number } | null;
  /** Example import cycles; null when cycle detection did not run. */
  cycles: { count: number; examples: ReadonlyArray<readonly string[]> } | null;
  /** Guided tour stops; empty when no tour could be derived. */
  tour: readonly TourStop[];
  tourSummary: string;
}

const MAX_LANGUAGES = 12;
const MAX_SCRIPTS = 20;
const MAX_ENTRY_POINTS = 12;
const MAX_CYCLE_EXAMPLES = 5;
const MAX_CYCLE_LENGTH = 8;

function isoDate(at: number): string {
  try {
    return new Date(at).toISOString();
  } catch {
    return String(at);
  }
}

function list(items: readonly string[]): string {
  return items.map((item) => `- ${item}`).join('\n');
}

/** Escape the characters that would break a Markdown table cell. */
function cell(text: string): string {
  return text.replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');
}

function percent(part: number, whole: number): string {
  if (whole <= 0) return '';
  return ` (${Math.round((part / whole) * 100)}%)`;
}

/** Render the report as Markdown. Pure and deterministic for a given input. */
export function buildRepoReport(input: RepoReportInput): string {
  const out: string[] = [];

  out.push(`# ${input.name} — repository overview`);
  out.push('');
  out.push(
    `Generated by Axiom on ${isoDate(input.generatedAt)} from on-device analysis only. No code left this machine to produce this report.`,
  );
  out.push('');
  out.push(`- **Workspace:** \`${input.root}\``);
  out.push(`- **Source files analysed:** ${input.totalFiles.toLocaleString()}`);
  if (input.monorepo) {
    out.push(
      `- **Monorepo:** yes${
        input.workspaces.length > 0 ? ` — ${input.workspaces.length} workspace(s)` : ''
      }`,
    );
  }
  out.push('');

  out.push('## What this project is');
  out.push('');
  if (input.frameworks.length > 0) {
    out.push(`**Frameworks detected:** ${input.frameworks.join(', ')}`);
    out.push('');
  }
  if (input.languages.length > 0) {
    const languageTotal = input.languages.reduce((sum, language) => sum + language.files, 0);
    out.push('| Language | Files |');
    out.push('| --- | --- |');
    for (const language of input.languages.slice(0, MAX_LANGUAGES)) {
      out.push(`| ${cell(language.name)} | ${language.files}${percent(language.files, languageTotal)} |`);
    }
    if (input.languages.length > MAX_LANGUAGES) {
      out.push(`| … ${input.languages.length - MAX_LANGUAGES} more | |`);
    }
  } else {
    out.push('No language breakdown was available.');
  }
  out.push('');

  out.push('## How to run it');
  out.push('');
  if (input.packageManagers.length > 0) {
    out.push(`**Package manager(s):** ${input.packageManagers.join(', ')}`);
    out.push('');
  }
  out.push(`**Tests:** ${input.testFramework ?? 'no test framework was detected'}`);
  out.push('');
  if (input.scripts.length > 0) {
    out.push('| Script | Command |');
    out.push('| --- | --- |');
    for (const script of input.scripts.slice(0, MAX_SCRIPTS)) {
      out.push(`| \`${cell(script.name)}\` | \`${cell(script.command)}\` |`);
    }
    if (input.scripts.length > MAX_SCRIPTS) {
      out.push(`| … ${input.scripts.length - MAX_SCRIPTS} more | |`);
    }
  } else {
    out.push('No scripts were detected.');
  }
  out.push('');

  out.push('## Where to start reading');
  out.push('');
  if (input.entryPoints.length > 0) {
    out.push('**Entry points:**');
    out.push(list(input.entryPoints.slice(0, MAX_ENTRY_POINTS).map((entry) => `\`${entry}\``)));
    out.push('');
  }
  if (input.tour.length > 0) {
    if (input.tourSummary) {
      out.push(input.tourSummary);
      out.push('');
    }
    for (const stop of input.tour) {
      const where = stop.path ? ` — \`${stop.path}\`` : '';
      out.push(`${stop.order + 1}. **${stop.title}**${where}`);
      out.push(`   ${stop.description}`);
    }
  } else {
    out.push('No guided tour could be derived for this project.');
  }
  out.push('');

  out.push('## Structure and coupling');
  out.push('');
  if (input.graph) {
    const density =
      input.graph.nodes > 0 ? (input.graph.edges / input.graph.nodes).toFixed(2) : '0.00';
    out.push(
      `The dependency graph has **${input.graph.nodes.toLocaleString()} files** connected by **${input.graph.edges.toLocaleString()} imports** (${density} imports per file on average).`,
    );
  } else {
    out.push('The dependency graph could not be built, so coupling was not analysed.');
  }
  out.push('');
  if (input.cycles === null) {
    out.push('Import-cycle detection did not run.');
  } else if (input.cycles.count === 0) {
    out.push('**No import cycles were found.**');
  } else {
    out.push(
      `**${input.cycles.count} import cycle(s) found.** Cycles make code hard to test and reason about; these are the shortest examples:`,
    );
    out.push('');
    for (const cycle of input.cycles.examples.slice(0, MAX_CYCLE_EXAMPLES)) {
      const shown = cycle.slice(0, MAX_CYCLE_LENGTH);
      const suffix = cycle.length > MAX_CYCLE_LENGTH ? ' → …' : '';
      out.push(`- ${shown.map((file) => `\`${file}\``).join(' → ')}${suffix}`);
    }
  }
  out.push('');

  out.push('---');
  out.push('');
  out.push(
    'Everything above is derived from static local analysis of this folder. It reports what was measured; anything that could not be analysed is stated as such rather than inferred.',
  );
  out.push('');

  return out.join('\n');
}

/** Default export filename for a report (safe on every platform). */
export function repoReportFileName(name: string, generatedAt: number): string {
  const safe = name.replace(/[^A-Za-z0-9._-]+/g, '-').replace(/^-+|-+$/g, '') || 'repo';
  const stamp = isoDate(generatedAt).replace(/[:.]/g, '-').replace(/Z$/, '');
  return `${safe}-overview-${stamp}.md`;
}
